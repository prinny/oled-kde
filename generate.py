def rgb(hex_color):
    h = hex_color.lstrip("#")
    return ",".join(str(int(h[i:i + 2], 16)) for i in (0, 2, 4))


def scale(hex_color, factor):
    h = hex_color.lstrip("#")
    return "%02X%02X%02X" % tuple(int(int(h[i:i + 2], 16) * factor) for i in (0, 2, 4))


