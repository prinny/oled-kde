"""Regenerate every OLED KDE artifact from one palette (standard library only).

Palette sources in oled-gnome (https://github.com/drkhn1234/oled-gnome):
GTK 3/4 colors and surfaces, the GNOME Shell stylesheet, and
palettes/ptyxis/OLED.palette. Where the GNOME source has no value:
  accent    = #22D3EE static fallback (the source follows the system
              accent dynamically; Plasma's accent setting overrides
              this in a Plasma session)
  positive  = #8AE234, neutral = #FCE94F (Ptyxis brights; conventional
              semantics instead of the GTK 4 warning/success pair)
  visited   = #AD7FA8 (Ptyxis bright magenta; source defines none)
  button bg = #161616 (pure black would erase Breeze button frames)

Static package files (metadata.json, plasmarc, contents/defaults and
the previews) are not generated here and are maintained by hand.
"""

