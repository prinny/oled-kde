def btop_theme():
    # Download gradient ends violet so it differs from upload at a glance.
    gradients = [(name, VISITED if name == "download" else NEGATIVE)
                 for name in ("temp", "cpu", "free", "cached", "available",
                              "used", "download", "upload")]
    lines = ["# SPDX-License-Identifier: MIT",
             "# OLED btop theme. Generated by generate.py; edit the palette there.", "",
             f'theme[main_bg]="#{BLACK}"', f'theme[main_fg]="#{WHITE}"',
             f'theme[title]="#{WHITE}"', f'theme[hi_fg]="#{ACCENT}"',
             f'theme[selected_bg]="#{HOVER}"', f'theme[selected_fg]="#{ACCENT}"',
             f'theme[inactive_fg]="#{DIM}"', f'theme[graph_text]="#{FG_INACTIVE}"',
             f'theme[meter_bg]="#{SURFACE}"', f'theme[proc_misc]="#{ACCENT}"', ""]
    lines += [f'theme[{box}_box]="#{BORDER}"' for box in ("cpu", "mem", "net", "proc")]
    lines += [f'theme[div_line]="#{BORDER}"']
    for name, end in gradients:
        lines += ["", f'theme[{name}_start]="#{ACCENT}"',
                  f'theme[{name}_mid]="#{POSITIVE}"', f'theme[{name}_end]="#{end}"']
    return "\n".join(lines) + "\n"


