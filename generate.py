def colors_file(plasma_subset=False):
    out = ["# OLED - pure-black color scheme ported from oled-gnome (MIT).",
           "# Generated by generate.py; edit the palette there.\n", EFFECTS]
    for group, (alt, normal) in GROUPS.items():
        fg = dict(FG)
        if group == "Colors:Selection":
            fg["ForegroundActive"] = fg["ForegroundNormal"] = fg["ForegroundInactive"] = BLACK
            fg["ForegroundLink"] = BLACK  # accent-on-accent would be invisible
        lines = [f"[{group}]",
                 f"BackgroundAlternate={rgb(alt)}",
                 f"BackgroundNormal={rgb(normal)}"]
        if not plasma_subset:  # Plasma desktoptheme derives these
            lines += [f"DecorationFocus={rgb(ACCENT)}",
                      f"DecorationHover={rgb(ACCENT)}"]
        keys = [k for k in fg if not (plasma_subset and k == "ForegroundActive")]
        lines += [f"{k}={rgb(fg[k])}" for k in sorted(keys, key=list(FG).index)]
        out.append("\n".join(lines) + "\n")
    out.append(f"""[General]
ColorScheme=OLED
Name=OLED
shadeSortColumn=true

[KDE]
contrast=4

[WM]
activeBackground={rgb(BLACK)}
activeBlend={rgb(WHITE)}
activeForeground={rgb(WHITE)}
inactiveBackground={rgb(BLACK)}
inactiveBlend={rgb(FG_INACTIVE)}
inactiveForeground={rgb(FG_BACKDROP)}
""")
    return "\n".join(out)


# --- Konsole ---------------------------------------------------------------
def konsole_colorscheme():
    lines = ["[General]", "Description=OLED", "Opacity=1", "Blur=false",
             "ColorRandomization=false", "",
             "[Background]", f"Color={rgb(BLACK)}", "",
             "[BackgroundFaint]", f"Color={rgb(BLACK)}", "",
             "[BackgroundIntense]", f"Color={rgb(SURFACE)}", ""]
    for i in range(8):
        for suffix, value in (("", ANSI[i]), ("Faint", scale(ANSI[i], 0.65)),
                              ("Intense", ANSI[i + 8])):
            lines += [f"[Color{i}{suffix}]", f"Color={rgb(value)}", ""]
    lines += ["[Foreground]", f"Color={rgb(WHITE)}", "",
              "[ForegroundFaint]", f"Color={rgb(FG_INACTIVE)}", "",
              "[ForegroundIntense]", f"Color={rgb(WHITE)}", ""]
    return "\n".join(lines)


